/**
 * QNX OS 8.0 measurement-harness generator.
 *
 * The generated C is a real, buildable program: one thread per modelled task
 * with the same priority and policy, the same mutex protocols, and real
 * channels. It reports the response time it actually observed, which closes the
 * loop between the model and the board.
 *
 * Only workload.h and workload_config.h are derived from the model. The C sources are static templates,
 * so a change in the measurement code always shows up in review, and a change
 * in the workload can never silently change how it is measured.
 */

import { readFileSync } from 'node:fs';
import type { DerivedModel } from '../core/derive.js';
import { taskPeriodUs } from '../core/derive.js';
import type { Segment, SystemModel, TaskModel } from '../core/model.js';
import { formatDuration, type Micros } from '../core/units.js';
import { TOOL_VERSION } from '../version.js';

export interface GeneratedFile {
  readonly path: string;
  readonly content: string;
}

export interface GenerateOptions {
  /** Measurement window. Defaults to one hyperperiod, capped at 10 s. */
  readonly durationUs?: Micros;
}

export interface GeneratedHarness {
  readonly files: readonly GeneratedFile[];
  /** Model features the harness cannot reproduce, stated rather than dropped. */
  readonly unsupported: readonly string[];
  readonly durationUs: Micros;
}

const POLICY_C: Record<string, string> = {
  fifo: 'SS_POLICY_FIFO',
  rr: 'SS_POLICY_RR',
  sporadic: 'SS_POLICY_SPORADIC',
};

const PROTOCOL_C: Record<string, string> = {
  none: 'SS_PROTO_NONE',
  inherit: 'SS_PROTO_INHERIT',
  protect: 'SS_PROTO_PROTECT',
};

export function generateQnxHarness(model: SystemModel, derived: DerivedModel, options: GenerateOptions = {}): GeneratedHarness {
  const unsupported: string[] = [];
  if (model.interrupts.sources.length > 0) {
    const names = model.interrupts.sources
      .map((source) => '"' + source.name + '" (' + formatDuration(source.periodUs) + ', ' + formatDuration(source.serviceUs) + ')')
      .join(', ');
    unsupported.push(
      'interrupt sources ' + names + ' are not reproduced: the harness runs threads, not ISR/IST handlers, ' +
        'so its response times exclude the interrupt interference the analysis includes. Compare against the ISR column, not the R column.',
    );
  }
  const durationUs = options.durationUs ?? Math.min(derived.hyperperiodUs, 10_000_000);
  const vars = {
    SYSTEM_NAME: model.name,
    VERSION: TOOL_VERSION,
    DURATION: formatDuration(durationUs),
  };
  const files: GeneratedFile[] = [
    { path: 'workload_config.h', content: emitWorkloadConfig(model) },
    { path: 'workload.h', content: emitWorkload(model, durationUs, unsupported) },
    { path: 'harness.c', content: template('harness.c') },
    { path: 'platform.h', content: template('platform.h') },
    { path: 'platform_qnx.c', content: template('platform_qnx.c') },
    { path: 'platform_posix.c', content: template('platform_posix.c') },
    { path: 'Makefile', content: render('Makefile.tmpl', vars) },
    { path: 'README.md', content: render('README.md.tmpl', vars) },
    { path: 'image.build.template', content: render('image.build.tmpl', vars) },
  ];
  return { files, unsupported, durationUs };
}

function template(name: string): string {
  return readFileSync(new URL('./templates/' + name, import.meta.url), 'utf8');
}

function render(name: string, vars: Readonly<Record<string, string>>): string {
  return template(name).replace(/\{\{([A-Z_]+)\}\}/g, (match, key: string) => vars[key] ?? match);
}

/**
 * The few generated facts the platform backends need on their own: the highest
 * priority the workload asks for (which decides the PROCMGR_AID_PRIORITY
 * request) and whether the model contains interrupt sources the harness cannot
 * reproduce.
 */
export function emitWorkloadConfig(model: SystemModel): string {
  const maxPriority = Math.max(
    1,
    ...model.tasks.map((task) => task.priority),
    ...model.channels.map((channel) => channel.basePriority),
  );
  const out: string[] = [];
  out.push('/*');
  out.push(' * Generated by Scheduloscope ' + TOOL_VERSION + ' from model "' + model.name + '".');
  out.push(' * Facts the platform backends need without the full workload tables.');
  out.push(' */');
  out.push('#ifndef SS_WORKLOAD_CONFIG_H');
  out.push('#define SS_WORKLOAD_CONFIG_H');
  out.push('');
  out.push('#define SS_MAX_PRIORITY ' + String(maxPriority));
  out.push('#define SS_HAS_INTERRUPTS ' + (model.interrupts.sources.length > 0 ? '1' : '0'));
  out.push('');
  out.push('#endif /* SS_WORKLOAD_CONFIG_H */');
  out.push('');
  return out.join('\n');
}

export function emitWorkload(model: SystemModel, durationUs: Micros, unsupported: string[]): string {
  const resourceIndex = new Map(model.resources.map((resource, index) => [resource.name, index]));
  const channelIndex = new Map(model.channels.map((channel, index) => [channel.name, index]));
  const out: string[] = [];

  out.push('/*');
  out.push(' * Generated by Scheduloscope ' + TOOL_VERSION + ' from model "' + model.name + '".');
  out.push(' * Regenerate from the YAML model instead of editing this file.');
  out.push(' */');
  out.push('#ifndef SS_WORKLOAD_H');
  out.push('#define SS_WORKLOAD_H');
  out.push('');
  out.push('#include "workload_config.h"');
  out.push('');
  out.push('#define SS_TASK_COUNT ' + String(model.tasks.length));
  out.push('#define SS_CHANNEL_COUNT ' + String(model.channels.length));
  out.push('#define SS_RESOURCE_COUNT ' + String(model.resources.length));
  out.push('#define SS_SERVER_COUNT ' + String(model.channels.reduce((sum, channel) => sum + channel.serverThreads, 0)));
  out.push('#define SS_DURATION_US ' + String(durationUs) + 'ull');
  out.push('#define SS_SYSTEM_NAME ' + cString(model.name));
  out.push('');
  out.push('typedef enum { SS_SEG_CPU = 0, SS_SEG_CS = 1, SS_SEG_RPC = 2, SS_SEG_SLEEP = 3 } ss_seg_kind;');
  out.push('typedef struct { ss_seg_kind kind; int index; unsigned us; } ss_segment;');
  out.push('');
  out.push('typedef struct {');
  out.push('    const char *name;');
  out.push('    int priority;');
  out.push('    int policy;');
  out.push('    int activation; /* 0 periodic, 1 sporadic, 2 aperiodic */');
  out.push('    unsigned period_us;');
  out.push('    unsigned mean_interarrival_us;');
  out.push('    unsigned deadline_us;');
  out.push('    unsigned offset_us;');
  out.push('    int sporadic_low_priority;');
  out.push('    unsigned sporadic_budget_us;');
  out.push('    unsigned sporadic_replenish_us;');
  out.push('    int sporadic_max_repl;');
  out.push('    const ss_segment *segments;');
  out.push('    int segment_count;');
  out.push('} ss_task_def;');
  out.push('');
  out.push('typedef struct { const char *name; int protocol; int ceiling; } ss_resource_def;');
  out.push('typedef struct {');
  out.push('    const char *name;');
  out.push('    int server_threads;');
  out.push('    int base_priority;');
  out.push('    int fixed_priority;');
  out.push('    const ss_segment *handler;');
  out.push('    int handler_count;');
  out.push('} ss_channel_def;');
  out.push('');

  if (model.resources.length > 0) {
    out.push('static const ss_resource_def ss_resources[] = {');
    for (const resource of model.resources) {
      out.push('    { ' + [cString(resource.name), PROTOCOL_C[resource.protocol] ?? 'SS_PROTO_INHERIT', String(resource.ceiling ?? 0)].join(', ') + ' },');
    }
    out.push('};');
    out.push('');
  }

  model.channels.forEach((channel, index) => {
    out.push('static const ss_segment ss_channel_' + String(index) + '_handler[] = { ' +
      segmentsToC(channel.handler, resourceIndex, channelIndex, unsupported, 'channel ' + channel.name) + ' };');
  });
  model.tasks.forEach((task, index) => {
    out.push('static const ss_segment ss_task_' + String(index) + '_segments[] = { ' +
      segmentsToC(task.segments, resourceIndex, channelIndex, unsupported, 'task ' + task.name) + ' };');
  });
  out.push('');

  if (model.channels.length > 0) {
    out.push('static const ss_channel_def ss_channel_defs[] = {');
    model.channels.forEach((channel, index) => {
      out.push('    { ' + [
        cString(channel.name),
        String(channel.serverThreads),
        String(channel.basePriority),
        channel.fixedPriority ? '1' : '0',
        'ss_channel_' + String(index) + '_handler',
        String(channel.handler.length),
      ].join(', ') + ' },');
    });
    out.push('};');
    out.push('');
  }

  out.push('static const ss_task_def ss_tasks[] = {');
  model.tasks.forEach((task, index) => {
    out.push('    ' + taskToC(task, index));
  });
  out.push('};');
  out.push('');
  out.push('#endif /* SS_WORKLOAD_H */');
  out.push('');
  return out.join('\n');
}

function taskToC(task: TaskModel, index: number): string {
  const periodic = task.activation.type === 'periodic';
  const sporadic = task.activation.type === 'sporadic';
  const activation = periodic ? 0 : sporadic ? 1 : 2;
  const period = task.activation.type === 'aperiodic' ? 0 : taskPeriodUs(task);
  const mean = task.activation.type === 'aperiodic' ? task.activation.meanInterarrivalUs : 0;
  const fields = [
    cString(task.name),
    String(task.priority),
    POLICY_C[task.policy] ?? 'SS_POLICY_FIFO',
    String(activation),
    String(period) + 'u',
    String(mean) + 'u',
    String(task.deadlineUs) + 'u',
    String(task.activation.offsetUs) + 'u',
    String(task.sporadic?.lowPriority ?? 0),
    String(task.sporadic?.initBudgetUs ?? 0) + 'u',
    String(task.sporadic?.replenishPeriodUs ?? 0) + 'u',
    String(task.sporadic?.maxReplenishments ?? 0),
    'ss_task_' + String(index) + '_segments',
    String(task.segments.length),
  ];
  return '{ ' + fields.join(', ') + ' }, /* ' + task.policy + ', deadline ' + formatDuration(task.deadlineUs) + ' */';
}

function segmentsToC(
  segments: readonly Segment[],
  resourceIndex: ReadonlyMap<string, number>,
  channelIndex: ReadonlyMap<string, number>,
  unsupported: string[],
  where: string,
): string {
  const out: string[] = [];
  for (const segment of segments) {
    switch (segment.kind) {
      case 'cpu':
        out.push('{ SS_SEG_CPU, 0, ' + String(segment.us) + 'u }');
        break;
      case 'cs':
        out.push('{ SS_SEG_CS, ' + String(resourceIndex.get(segment.resource) ?? 0) + ', ' + String(segment.workUs) + 'u }');
        break;
      case 'rpc':
        out.push('{ SS_SEG_RPC, ' + String(channelIndex.get(segment.channel) ?? 0) + ', 0u } /* ' + segment.channel + ' */');
        break;
      case 'sleep':
        out.push('{ SS_SEG_SLEEP, 0, ' + String(segment.us) + 'u }');
        break;
      case 'yield':
        unsupported.push(where + ': yield is not reproduced by the harness, which measures response time rather than scheduling order.');
        break;
      case 'setPriority':
        unsupported.push(where + ': setPriority is not reproduced; the thread keeps its declared priority.');
        break;
    }
  }
  if (out.length === 0) out.push('{ SS_SEG_CPU, 0, 0u }');
  return out.join(', ');
}

function cString(value: string): string {
  return '"' + value.split('\\').join('\\\\').split('"').join('\\"') + '"';
}
